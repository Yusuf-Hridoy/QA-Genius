"""The matrix as a runnable Playwright config and as a CSV for manual runs.

Rows Playwright cannot drive (Edge on a phone, Firefox on a tablet) stay in the
CSV and are counted on the page; they are simply not projects.
"""

import csv
import io
import json

from qagenius.pairwise import Matrix
from qagenius.test_case_exports import safe_cell
from qagenius.test_matrix_defaults import playwright_project

HEADER = "Generated by QA-Genius. {runs} runs cover all {pairs} pairs of your factors."
MANUAL_NOTE = "Manual-only runs are in the CSV."


def _rows_as_dicts(matrix: Matrix) -> list[dict[str, str]]:
    names = [factor.name for factor in matrix.factors]
    return [dict(zip(names, row)) for row in matrix.rows]


def projects(matrix: Matrix) -> list[dict]:
    """One Playwright project per row, manual-only rows marked rather than dropped."""
    built = []
    for index, row in enumerate(_rows_as_dicts(matrix), start=1):
        project = playwright_project(row)
        project["name"] = f"M{index:02d} · " + " · ".join(str(value) for value in row.values())
        built.append(project)
    return built


def _ts_value(value) -> str:
    """A JS literal. json.dumps gives correct escaping for strings and dicts."""
    return json.dumps(value, ensure_ascii=False)


def _project_block(project: dict) -> list[str]:
    lines = ["    {", f"      name: {_ts_value(project['name'])},"]
    settings = []
    if project.get("device"):
        settings.append(f"...devices[{_ts_value(project['device'])}]")
    for key in ("channel", "locale", "colorScheme", "storageState"):
        if project.get(key):
            settings.append(f"{key}: {_ts_value(project[key])}")
    if settings:
        lines.append("      use: { " + ", ".join(settings) + " },")
    if project.get("metadata"):
        lines.append(f"      metadata: {_ts_value(project['metadata'])},")
    lines.append("    },")
    return lines


def to_playwright_config(matrix: Matrix) -> str:
    """playwright.matrix.config.ts — one project per automatable run."""
    automated = [one for one in projects(matrix) if not one.get("manual_only")]
    manual = len(matrix.rows) - len(automated)
    header = HEADER.format(runs=len(matrix.rows), pairs=matrix.covered_pairs)
    lines = [
        f"// {header}",
    ]
    if manual:
        lines.append(f"// {manual} of them cannot be driven by Playwright. {MANUAL_NOTE}")
    lines += [
        "import { defineConfig, devices } from '@playwright/test';",
        "",
        "export default defineConfig({",
        "  testDir: './tests',",
        "  projects: [",
    ]
    for project in automated:
        lines.extend(_project_block(project))
    lines += ["  ],", "});", ""]
    return "\n".join(lines)


def to_csv(matrix: Matrix) -> bytes:
    """UTF-8 with a BOM, so Excel opens it without an import step."""
    names = [factor.name for factor in matrix.factors]
    buffer = io.StringIO()
    writer = csv.writer(buffer, quoting=csv.QUOTE_MINIMAL, lineterminator="\r\n")
    writer.writerow(["Run", *names, "Automated"])
    for index, (row, project) in enumerate(zip(matrix.rows, projects(matrix)), start=1):
        automated = "Manual only" if project.get("manual_only") else "Yes"
        writer.writerow(
            [f"M{index:02d}", *[safe_cell(value) for value in row], automated]
        )
    return ("﻿" + buffer.getvalue()).encode("utf-8")


def manual_only_count(matrix: Matrix) -> int:
    return sum(1 for project in projects(matrix) if project.get("manual_only"))
