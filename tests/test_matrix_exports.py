"""A runnable Playwright config and a CSV a manual tester can work from."""

from qagenius.automation_checks import basic_js_check
from qagenius.pairwise import Factor, build_matrix
from qagenius.test_matrix_defaults import STANDARD_FACTORS, STANDARD_RULES
from qagenius.test_matrix_exports import (
    manual_only_count,
    projects,
    to_csv,
    to_playwright_config,
)

STANDARD = build_matrix(STANDARD_FACTORS, STANDARD_RULES)
SMALL = build_matrix(
    [
        Factor("Browser", ("Chrome", "Safari")),
        Factor("Device", ("Desktop", "Phone")),
    ],
    [],
)


def csv_lines(matrix) -> list[str]:
    return to_csv(matrix).decode("utf-8").lstrip("﻿").strip().split("\r\n")


# ------------------------------------------------------------------- config


def test_the_generated_config_passes_the_basic_syntax_check():
    """The same check the Automation desk runs over generated code."""
    assert basic_js_check(to_playwright_config(STANDARD)) is None


def test_the_config_imports_what_it_uses():
    config = to_playwright_config(STANDARD)
    assert "import { defineConfig, devices } from '@playwright/test';" in config
    assert "export default defineConfig({" in config
    assert "testDir: './tests'," in config


def test_there_is_one_project_per_automatable_run():
    config = to_playwright_config(STANDARD)
    automated = len(STANDARD.rows) - manual_only_count(STANDARD)
    assert config.count("      name: ") == automated
    assert manual_only_count(STANDARD) >= 1  # Edge on a phone


def test_a_manual_only_run_is_left_out_of_the_config_but_counted_in_the_header():
    config = to_playwright_config(STANDARD)
    assert "cannot be driven by Playwright" in config
    assert "Manual-only runs are in the CSV." in config


def test_the_header_states_the_runs_and_the_pairs():
    config = to_playwright_config(STANDARD)
    assert (
        f"// Generated by QA-Genius. {len(STANDARD.rows)} runs cover all "
        f"{STANDARD.covered_pairs} pairs of your factors." in config
    )


def test_every_project_name_is_unique_and_numbered():
    names = [project["name"] for project in projects(STANDARD)]
    assert len(set(names)) == len(names)
    assert names[0].startswith("M01 · ")
    assert " · " in names[0]


def test_the_config_carries_the_device_channel_and_session():
    config = to_playwright_config(STANDARD)
    assert '...devices["Desktop Chrome"]' in config
    assert 'channel: "msedge"' in config
    assert 'storageState: "auth/user.json"' in config


def test_a_locale_and_colour_scheme_reach_the_config():
    matrix = build_matrix(
        [
            Factor("Browser", ("Chrome", "Safari")),
            Factor("Language", ("EN", "AR")),
            Factor("Color scheme", ("Light", "Dark")),
        ],
        [],
    )
    config = to_playwright_config(matrix)
    assert 'locale: "ar-SA"' in config
    assert 'colorScheme: "dark"' in config


def test_an_unknown_factor_rides_along_as_metadata():
    matrix = build_matrix(
        [
            Factor("Browser", ("Chrome", "Safari")),
            Factor("Payment method", ("Card", "Gift card")),
        ],
        [],
    )
    config = to_playwright_config(matrix)
    assert 'metadata: {"payment_method":' in config


def test_a_value_with_a_quote_cannot_break_the_config():
    matrix = build_matrix(
        [
            Factor("Browser", ("Chrome", "Safari")),
            Factor("Note", ('say "hi"', "plain")),
        ],
        [],
    )
    config = to_playwright_config(matrix)
    assert basic_js_check(config) is None
    assert '\\"hi\\"' in config


# ---------------------------------------------------------------------- csv


def test_the_csv_header_names_every_factor():
    assert csv_lines(STANDARD)[0] == "Run,Browser,Device,Signed in,Automated"


def test_the_csv_has_a_line_per_run():
    assert len(csv_lines(STANDARD)) == len(STANDARD.rows) + 1


def test_the_csv_says_which_runs_are_manual():
    body = to_csv(STANDARD).decode("utf-8")
    assert "Manual only" in body
    assert body.count("Manual only") == manual_only_count(STANDARD)


def test_the_csv_opens_in_excel_without_an_import_step():
    assert to_csv(SMALL).startswith("﻿".encode("utf-8"))


def test_a_value_that_looks_like_a_formula_is_defused():
    matrix = build_matrix(
        [
            Factor("Browser", ("Chrome", "Safari")),
            Factor("Note", ("=SUM(A1:A9)", "plain")),
        ],
        [],
    )
    body = to_csv(matrix).decode("utf-8")
    assert "'=SUM(A1:A9)" in body
    assert ",=SUM(A1:A9)" not in body


def test_the_runs_are_numbered_the_same_way_in_both_exports():
    config = to_playwright_config(SMALL)
    rows = csv_lines(SMALL)[1:]
    assert rows[0].startswith("M01,")
    assert "M01 · " in config
